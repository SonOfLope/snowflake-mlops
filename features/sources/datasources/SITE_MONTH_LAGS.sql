SELECT
  SITE_ID,
  TO_TIMESTAMP_NTZ(MONTH) AS MONTH,
  TONNES,
  LAG(TONNES, 1) OVER (PARTITION BY SITE_ID ORDER BY MONTH) AS LAG_1,
  LAG(TONNES, 2) OVER (PARTITION BY SITE_ID ORDER BY MONTH) AS LAG_2,
  LAG(TONNES, 3) OVER (PARTITION BY SITE_ID ORDER BY MONTH) AS LAG_3,
  MONTH(MONTH) AS MONTH_NUM
FROM WORKSPACE.SRC_SITE_MONTH
